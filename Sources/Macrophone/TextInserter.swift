import AppKit
import CoreGraphics

/// Puts text into the focused app with ⌘V — length-independent, and terminals receive it as a
/// bracketed paste, so newlines don't submit.
///
/// The string is offered lazily through a data provider, so we learn the moment the target app
/// actually reads it; the previous clipboard is restored shortly after that read rather than after
/// a guessed delay. Marker types tell clipboard managers to skip the entry.
@MainActor
final class TextInserter: NSObject, NSPasteboardItemDataProvider {
    static let shared = TextInserter()

    private var pendingText: String?
    private var saved: [NSPasteboardItem]?
    private var ourChangeCount = -1
    private var restoreWork: DispatchWorkItem?

    /// Restore this long after the target app read the text…
    private let restoreAfterRead: TimeInterval = 0.2

    private static let markers = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
    ].map { NSPasteboard.PasteboardType($0) }

    /// …or after `fallbackDelay` if it never reads it.
    func insert(_ text: String, submit: Bool, restoreClipboard: Bool, fallbackDelay: TimeInterval) {
        let pasteboard = NSPasteboard.general
        // Keep the user's clipboard from before the first of several quick insertions.
        if restoreClipboard, saved == nil { saved = snapshot(pasteboard) }

        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        if restoreClipboard {
            item.setDataProvider(self, forTypes: [.string])
        } else {
            item.setString(text, forType: .string)
        }
        for marker in Self.markers { item.setData(Data(), forType: marker) }
        pendingText = text
        pasteboard.writeObjects([item])
        ourChangeCount = pasteboard.changeCount

        KeySender.post(key: KeySender.vKey, flags: .maskCommand)
        if submit {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.04) { KeySender.post(key: 36, flags: []) } // Return
        }
        if restoreClipboard { scheduleRestore(after: fallbackDelay) }
    }

    nonisolated func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                                provideDataForType type: NSPasteboard.PasteboardType) {
        MainActor.assumeIsolated {
            item.setString(pendingText ?? "", forType: type)
            scheduleRestore(after: restoreAfterRead)
        }
    }

    nonisolated func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}

    private func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private func scheduleRestore(after delay: TimeInterval) {
        restoreWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.restore() }
        restoreWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
    }

    private func restore() {
        let pasteboard = NSPasteboard.general
        defer {
            saved = nil
            pendingText = nil
        }
        // Someone copied something else in the meantime: leave their clipboard alone.
        guard pasteboard.changeCount == ourChangeCount, let saved else { return }
        pasteboard.clearContents()
        if !saved.isEmpty { pasteboard.writeObjects(saved) }
    }
}

enum KeySender {
    /// kVK_ANSI_V: the V position on ANSI layouts.
    static let vKey: CGKeyCode = 9

    static func post(key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false) else { return }
        // Set flags explicitly so modifiers still physically held (e.g. Shift to submit) don't leak in.
        down.flags = flags
        up.flags = flags
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }
}
